/*!
Las sentencias en Rust son instrucciones que realizan una acción pero no producen un valor.
Por ejemplo, una declaración `let` o una expresión terminada en `;`.
*/

/**
Las sentencias ejecutan acciones.
En este ejemplo declaramos variables y usamos un punto y coma para convertir una suma en sentencia.
*/
pub fn sentencia()  {
    let a = 1;
    let b = 2;
    a + b;
}